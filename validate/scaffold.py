"""Turn a Sherlock `check --json` report into a precision-study skeleton.

A FAIL from `agentcheck check` is a path in the model, not a demonstrated
attack. The precision study (PRECISION.md) asks how many FAILs reproduce as real
model behavior. Transcribing each finding into a `validate.Scenario` by hand is
the tedious part; this does it. It reads the findings and writes a scenarios
module with one stub per FAIL -- the secret's source, the sink it reaches and
the untrusted inputs already filled in from the finding -- leaving `run_app`,
the one piece only you can write, as a TODO. An un-wired stub reports ERROR, so
`agentcheck validate` shows you exactly what is left to fill in.

    agentcheck check POLICY --config fleet.json --json findings.json
    python -m validate.scaffold findings.json scenarios.py
    # fill in run_app for each stub, then:
    agentcheck validate scenarios.py

Only run the result against a fleet you own or are authorized to test. See
PRECISION.md for the protocol and the safety envelope.
"""

from __future__ import annotations

import json
import re
import sys

from .finding import FindingShape, failing


def _ident(s: str, fallback: str) -> str:
    """A safe-ish identifier/label fragment from an arbitrary name."""
    out = re.sub(r"[^0-9A-Za-z]+", "_", s).strip("_")
    return out or fallback


def _slug(s: str, used: set[str]) -> str:
    base = _ident(s.lower(), "finding")
    name, i = base, 2
    while name in used:
        name, i = f"{base}_{i}", i + 1
    used.add(name)
    return name


def _dict_literal(items: dict[str, str]) -> str:
    return "{" + ", ".join(f"{k!r}: {v}" for k, v in items.items()) + "}"


def stub(name: str, sh: FindingShape) -> str:
    """Python source for one scenario builder function."""
    canary_label = _ident(sh.label or sh.source or "secret", "secret")
    sink = sh.sink or "out"
    untrusted = sh.untrusted or ["input"]

    canaries = _dict_literal({canary_label: f"Canary({canary_label!r})"})
    sinks = _dict_literal({sink: f"LocalSink({sink!r})"})
    unt = _dict_literal({u: "MarkerInput()" for u in untrusted})

    src_note = f"  # secret source: {sh.source}" if sh.source else ""
    kind_note = ("# nobody broken into: a flow driven by untrusted text alone, which this "
                 "harness reproduces directly."
                 if sh.pure_injection else
                 f"# the model assumed these agents were already malicious: {', '.join(sh.broken)}. "
                 "Reproduction means simulating that (a compromised node), not a pure injection.")
    doc_path = "\n".join("      " + line for line in sh.path) or "      (no path recorded)"
    expect = f"({canary_label!r}, {sink!r})" if (sh.label or sh.source) and sh.sink else "None"

    return f'''def scenario_{name}():
    """{sh.policy or name}
    {kind_note}
    model's path:
{doc_path}
    """
    canaries = {canaries}{src_note}
    sinks = {sinks}            # outward action(s): record, do not send
    untrusted = {unt}          # attacker-controlled input(s)
    return Scenario(
        run_app=_unwired({name!r}),   # TODO: replace with YOUR compiled fleet
        canaries=canaries, sinks=sinks, untrusted=untrusted,
        expect={expect},
    )
'''


_HEADER = '''"""Precision-study scenarios generated by `validate.scaffold`.

Each stub pins the roles one FAIL finding describes; you fill in run_app with
YOUR fleet (place each Canary at its source tool/state, replace each outward
tool with the matching LocalSink, feed inputs[<key>] into the untrusted input).
Until you do, a stub reports ERROR, not a false REPRODUCED/BLOCKED.

    agentcheck validate {thisfile}

Run only against a fleet you own or are authorized to test. See PRECISION.md.
sherlock must be importable (pip install, or run from the repo root).
"""

from validate import Canary, LocalSink, MarkerInput, Scenario


def _unwired(name):
    def run_app(inputs):
        raise NotImplementedError(
            name + ": wire your fleet here -- place each Canary at its source "
            "tool/state, replace each outward tool with the matching LocalSink, "
            "and feed inputs[<key>] into the untrusted input.")
    return run_app


'''


def scaffold(rows: list[dict], thisfile: str = "scenarios.py") -> str:
    """The full scenarios-module source for the FAIL rows of a check report."""
    shapes = failing(rows)
    used: set[str] = set()
    named = [(_slug(sh.policy or "finding", used), sh) for sh in shapes]
    parts = [_HEADER.format(thisfile=thisfile)]
    parts += [stub(name, sh) for name, sh in named]
    reg = ",\n".join(f"        {name!r}: scenario_{name}()" for name, _ in named)
    parts.append("def scenarios():\n    return {\n" + reg + ("\n" if reg else "") + "    }\n")
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("findings", help="JSON written by `agentcheck check --json`")
    ap.add_argument("out", nargs="?", help="write the scenarios module here (default: stdout)")
    args = ap.parse_args(argv)
    data = json.load(open(args.findings))
    rows = data if isinstance(data, list) else (data.get("policies") or data.get("results") or [])
    if not isinstance(rows, list):
        print("error: expected a list of findings (the output of `check --json`)", file=sys.stderr)
        return 2
    src = scaffold(rows, thisfile=args.out or "scenarios.py")
    n = src.count("def scenario_")
    if args.out:
        with open(args.out, "w") as f:
            f.write(src)
        print(f"wrote {args.out}: {n} stub{'' if n == 1 else 's'} "
              f"(fill in run_app for each, then: agentcheck validate {args.out})")
    else:
        sys.stdout.write(src)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
